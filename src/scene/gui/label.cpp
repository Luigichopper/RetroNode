Label::Label() {
    name = "Label";
    text = "Label";
    z_index = 100;
}

void Label::_ready() {
    // Generate 128x64 8x8 font atlas texture
    std::vector<uint8_t> pixels(128 * 64 * 4, 0);

    for (int idx = 0; idx < 96; ++idx) {
        int gx = (idx % 16) * 8;
        int gy = (idx / 16) * 8;

        for (int y = 0; y < 8; ++y) {
            uint8_t row = font_8x8_basic[idx][y];
            for (int x = 0; x < 8; ++x) {
                if (row & (1 << (7 - x))) {
                    int px = gx + x;
                    int py = gy + y;
                    int p_idx = (py * 128 + px) * 4;
                    pixels[p_idx + 0] = 255;
                    pixels[p_idx + 1] = 255;
                    pixels[p_idx + 2] = 255;
                    pixels[p_idx + 3] = 255;
                }
            }
        }
    }

    font_texture_id = TextureServer::get()->create_procedural_texture(
        "retro_font_8x8",
        128,
        64,
        pixels.data()
    );
}

void Label::get_property_list(std::vector<PropertyInfo>& out_list) const {
    Control::get_property_list(out_list);
    out_list.push_back({ StringName("text"), VariantType::STRING });
    out_list.push_back({ StringName("text_color"), VariantType::COLOR });
}

Variant Label::get(const StringName& p_name) const {
    if (p_name == StringName("text")) return Variant(text);
    if (p_name == StringName("text_color")) return Variant(text_color);
    return Control::get(p_name);
}

bool Label::set(const StringName& p_name, const Variant& p_value) {
    if (p_name == StringName("text")) {
        set_text(p_value.as_string());
        return true;
    }
    if (p_name == StringName("text_color")) {
        text_color = p_value.as_color();
        return true;
    }
    return Control::set(p_name, p_value);
}

void Label::_process(float delta) {
    (void)delta;
    if (!is_visible_in_tree()) return;
    if (text.empty()) return;

    Vector2Fixed global_pos = get_global_control_position();
    Vector2Fixed global_prev_pos = get_global_control_previous_position();
    Vector2Fixed cam_offset = VisualServer::get()->get_camera_offset();

    // UI screen-space offset adjustment
    Vector2Fixed ui_draw_pos = global_pos + cam_offset;
    Vector2Fixed ui_prev_draw_pos = global_prev_pos + cam_offset;

    Vector2Fixed glyph_size = Vector2Fixed::from_floats(8.0f, 8.0f);

    for (size_t i = 0; i < text.length(); ++i) {
        char ch = text[i];
        int ascii_idx = static_cast<int>(ch) - 32;
        if (ascii_idx < 0 || ascii_idx >= 96) ascii_idx = 0;

        int src_x = (ascii_idx % 16) * 8;
        int src_y = (ascii_idx / 16) * 8;

        Fixed16 char_offset_x = Fixed16::from_int(static_cast<int>(i) * 8);

        Vector2Fixed char_pos(ui_draw_pos.x + char_offset_x, ui_draw_pos.y);
        Vector2Fixed char_prev_pos(ui_prev_draw_pos.x + char_offset_x, ui_prev_draw_pos.y);

        Rect2Fixed src_rect = Rect2Fixed::from_floats(
            static_cast<float>(src_x),
            static_cast<float>(src_y),
            8.0f,
            8.0f
        );

        VisualServer::get()->submit_draw_sprite(
            char_pos,
            char_prev_pos,
            glyph_size,
            src_rect,
            font_texture_id,
            z_index,
            text_color
        );
    }
}

